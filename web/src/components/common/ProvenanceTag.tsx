import React from 'react';
import { Cog, Sparkles, User } from 'lucide-react';
import './ProvenanceTag.css';

export type ProvenanceKind = 'rule-based' | 'ai-proposed' | 'human-entered';

interface ProvenanceTagProps {
  kind: ProvenanceKind;
  source?: string;
  timestamp?: string;
  className?: string;
}

export const ProvenanceTag: React.FC<ProvenanceTagProps> = ({
  kind,
  source,
  timestamp,
  className = '',
}) => {
  const getMeta = () => {
    switch (kind) {
      case 'rule-based':
        return {
          icon: Cog,
          label: 'Rule-based',
          tooltip: source ? `Generated by rule: ${source}` : 'Generated by deterministic rule',
        };
      case 'ai-proposed':
        return {
          icon: Sparkles,
          label: 'AI-proposed',
          tooltip: source ? `Proposed by agent: ${source}` : 'Proposed by AI reasoning model',
        };
      case 'human-entered':
        return {
          icon: User,
          label: 'Human-entered',
          tooltip: source ? `Entered by: ${source}` : 'Entered by authorized human',
        };
    }
  };

  const { icon: Icon, label, tooltip } = getMeta();
  const fullTooltip = [tooltip, timestamp ? `at ${timestamp}` : ''].filter(Boolean).join(' ');

  return (
    <span
      className={`ev-provenance-tag ev-provenance-${kind} ${className}`}
      tabIndex={0}
      title={fullTooltip}
      role="note"
      aria-label={`${label}. ${fullTooltip}`}
    >
      <Icon size={12} className="ev-provenance-icon" aria-hidden="true" />
      <span className="ev-provenance-label">{label}</span>
      {source && <span className="ev-provenance-source">({source})</span>}
    </span>
  );
};
